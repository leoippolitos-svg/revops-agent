"""Render the data catalog as one readable page: docs/catalog.md.

The catalog is the set of model and column descriptions in the dbt schema.yml
files (ADR-0002). This script turns them into a page for people, and for each
model lists the context documents that use it, so a reader can go from a table
to what it means for the business.

Run from the repository root:
    python tools/build_catalog.py           # rewrite docs/catalog.md
    python tools/build_catalog.py --check   # fail if docs/catalog.md is out of date

The page is generated. Edit the schema.yml files, never the page.
"""

import re
import sys
from pathlib import Path

import yaml

# Gold first: it is the layer the agent reads.
LAYERS = [
    ("gold", "Gold", "Business grain, ready to use. The agent and the MCP server read only this layer."),
    ("silver", "Silver", "Cleaned, typed, one row per entity. The step between raw data and gold."),
]
OUTPUT = Path("docs/catalog.md")
ANNOTATION = re.compile(r"\[\[([a-z]+\.[a-z_]+)(?:\.[a-z_]+)?\]\]")


def load_models(root: Path, layer: str) -> list[dict]:
    schema = root / "pipeline" / "dbt" / "models" / layer / "schema.yml"
    return (yaml.safe_load(schema.read_text(encoding="utf-8")) or {}).get("models", [])


def documents_using(root: Path) -> dict[str, list[tuple[str, str]]]:
    """Map "gold.mrr_monthly" to the (id, title) of every document that mentions it."""
    used: dict[str, list[tuple[str, str]]] = {}
    for path in sorted((root / "context" / "concepts").glob("*.md")):
        text = path.read_text(encoding="utf-8")
        front = yaml.safe_load(text.split("---", 2)[1]) or {}
        for model in sorted(set(ANNOTATION.findall(text))):
            used.setdefault(model, []).append((front["id"], front["title"]))
    return used


def cell(text: str) -> str:
    """Make a description safe inside a markdown table cell."""
    return " ".join(str(text).split()).replace("|", "\\|")


def render(root: Path) -> str:
    used = documents_using(root)
    lines = [
        "# Data catalog",
        "",
        "<!-- Generated by tools/build_catalog.py from the dbt schema.yml files. Do not edit by hand. -->",
        "",
        "What every table and column is. For what a metric *means* for the business, follow the "
        "context document linked under each table.",
        "",
    ]
    for layer, title, summary in LAYERS:
        models = load_models(root, layer)
        lines += [f"## {title}", "", summary, ""]
        lines += [f"- [`{layer}.{m['name']}`](#{layer}{m['name'].replace('_', '')})" for m in models]
        lines.append("")
        for model in models:
            name = f"{layer}.{model['name']}"
            # An anchor that is the same for every renderer, since heading ids differ.
            lines += [f'<a id="{layer}{model["name"].replace("_", "")}"></a>', "", f"### `{name}`", "",
                      cell(model["description"]), ""]
            documents = used.get(name, [])
            if documents:
                links = ", ".join(f"[{t}](../context/concepts/{i}.md)" for i, t in documents)
                lines += [f"**Context:** {links}", ""]
            lines += ["| Column | Description |", "|---|---|"]
            lines += [f"| `{c['name']}` | {cell(c['description'])} |" for c in model["columns"]]
            lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv: list[str]) -> int:
    root = Path(".")
    page = render(root)
    if "--check" in argv:
        current = (root / OUTPUT).read_text(encoding="utf-8") if (root / OUTPUT).is_file() else ""
        if current != page:
            print(f"ERROR {OUTPUT} is out of date; run: python tools/build_catalog.py")
            return 1
        print(f"{OUTPUT} is up to date.")
        return 0
    (root / OUTPUT).write_text(page, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
